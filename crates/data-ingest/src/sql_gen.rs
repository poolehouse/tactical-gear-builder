//! `seed.sql` generation.
//!
//! DDL and INSERTs are written in the common PostgreSQL/SQLite subset:
//! `TEXT` ids, `INTEGER` grid dimensions and prices, JSON payloads in `TEXT`
//! columns, and `ON CONFLICT ... DO UPDATE` upserts so the seed is idempotent
//! on re-runs.

use crate::Catalog;
use core_engine::graph::{AdapterBridge, ComponentSpec, MountSlot, PlatformSpec};
use core_engine::pricing::{Colorway, VendorOffer};
use core_engine::regulation::RolePreset;
use serde::Serialize;

/// Render the full `seed.sql` for a catalog: DDL followed by upserts for
/// platforms, their mount slots, components, adapter bridges, and role
/// presets.
pub fn generate_seed_sql(catalog: &Catalog) -> String {
    let mut sql = String::new();
    sql.push_str("-- seed.sql generated by data-ingest (do not edit by hand)\n");
    sql.push_str("-- Compatible with PostgreSQL and SQLite.\n\n");
    sql.push_str("BEGIN TRANSACTION;\n\n");
    ddl(&mut sql);
    platforms(&mut sql, &catalog.platforms);
    components(&mut sql, &catalog.components);
    adapter_bridges(&mut sql, &catalog.adapter_bridges);
    role_presets(&mut sql, &catalog.role_presets);
    sql.push_str("COMMIT;\n");
    sql
}

/// Emit the `CREATE TABLE IF NOT EXISTS` statements.
fn ddl(sql: &mut String) {
    sql.push_str(
        "CREATE TABLE IF NOT EXISTS platforms (\n\
         \x20   id TEXT PRIMARY KEY,\n\
         \x20   sku TEXT NOT NULL,\n\
         \x20   name TEXT NOT NULL,\n\
         \x20   category TEXT, -- PlatformCategory, NULL in legacy seeds\n\
         \x20   plate_cuts TEXT NOT NULL, -- JSON array of PlateCut\n\
         \x20   sizes TEXT NOT NULL, -- JSON array of Size\n\
         \x20   msrp_cents INTEGER NOT NULL,\n\
         \x20   vendor_offers TEXT NOT NULL, -- JSON array of VendorOffer\n\
         \x20   allowed_colorways TEXT NOT NULL, -- JSON array of Colorway\n\
         \x20   default_colorway TEXT NOT NULL -- Colorway variant name\n\
         );\n\n",
    );
    sql.push_str(
        "CREATE TABLE IF NOT EXISTS mount_slots (\n\
         \x20   platform_id TEXT NOT NULL REFERENCES platforms(id) ON DELETE CASCADE,\n\
         \x20   slot_id TEXT NOT NULL,\n\
         \x20   label TEXT NOT NULL,\n\
         \x20   interface TEXT NOT NULL,\n\
         \x20   anchor TEXT NOT NULL, -- JSON AnchorBox2D\n\
         \x20   pals_cols INTEGER,\n\
         \x20   pals_rows INTEGER,\n\
         \x20   PRIMARY KEY (platform_id, slot_id)\n\
         );\n\n",
    );
    sql.push_str(
        "CREATE TABLE IF NOT EXISTS components (\n\
         \x20   id TEXT PRIMARY KEY,\n\
         \x20   sku TEXT NOT NULL,\n\
         \x20   name TEXT NOT NULL,\n\
         \x20   kind TEXT NOT NULL,\n\
         \x20   interface TEXT NOT NULL,\n\
         \x20   anchor TEXT NOT NULL, -- JSON AnchorBox2D\n\
         \x20   pals_cols INTEGER,\n\
         \x20   pals_rows INTEGER,\n\
         \x20   msrp_cents INTEGER NOT NULL,\n\
         \x20   vendor_offers TEXT NOT NULL, -- JSON array of VendorOffer\n\
         \x20   allowed_colorways TEXT NOT NULL, -- JSON array of Colorway\n\
         \x20   default_colorway TEXT NOT NULL, -- Colorway variant name\n\
         \x20   capabilities TEXT NOT NULL -- JSON array of CapabilityTag\n\
         );\n\n",
    );
    sql.push_str(
        "CREATE TABLE IF NOT EXISTS adapter_bridges (\n\
         \x20   id TEXT PRIMARY KEY,\n\
         \x20   sku TEXT NOT NULL,\n\
         \x20   name TEXT NOT NULL,\n\
         \x20   platform_interface TEXT NOT NULL,\n\
         \x20   component_interface TEXT NOT NULL,\n\
         \x20   anchor TEXT NOT NULL, -- JSON AnchorBox2D\n\
         \x20   msrp_cents INTEGER NOT NULL,\n\
         \x20   vendor_offers TEXT NOT NULL, -- JSON array of VendorOffer\n\
         \x20   allowed_colorways TEXT NOT NULL, -- JSON array of Colorway\n\
         \x20   default_colorway TEXT NOT NULL -- Colorway variant name\n\
         );\n\n",
    );
    sql.push_str(
        "CREATE TABLE IF NOT EXISTS role_presets (\n\
         \x20   preset_id TEXT PRIMARY KEY,\n\
         \x20   name TEXT NOT NULL,\n\
         \x20   role TEXT, -- OperationalRole variant name, NULL for policy-only presets\n\
         \x20   policy TEXT NOT NULL, -- RegulationPolicy variant name\n\
         \x20   platform_sku TEXT NOT NULL,\n\
         \x20   default_colorway TEXT NOT NULL, -- Colorway variant name\n\
         \x20   placements TEXT NOT NULL -- JSON array of PresetPlacement\n\
         );\n\n",
    );
}

/// Escape a SQL single-quoted string literal.
fn esc(s: &str) -> String {
    s.replace('\'', "''")
}

/// Serialize a serde value to a compact JSON literal, escaped for SQL.
fn json<T: Serialize + ?Sized>(value: &T) -> String {
    esc(&serde_json::to_string(value).expect("engine types always serialize"))
}

/// Serialize a unit enum variant to its bare variant name.
fn variant<T: Serialize>(value: &T) -> String {
    serde_json::to_value(value)
        .ok()
        .and_then(|v| v.as_str().map(str::to_owned))
        .unwrap_or_default()
}

/// The shared pricing column list for platforms, components, and adapters.
fn pricing_columns(
    msrp_cents: u32,
    offers: &[VendorOffer],
    colorways: &[Colorway],
    default_colorway: Colorway,
) -> (String, String) {
    (
        format!("{}, '{}', '{}', '{}'", msrp_cents, json(offers), json(colorways), variant(&default_colorway)),
        "msrp_cents = excluded.msrp_cents, vendor_offers = excluded.vendor_offers, allowed_colorways = excluded.allowed_colorways, default_colorway = excluded.default_colorway".to_owned(),
    )
}

/// Upsert one platform row.
fn platform_row(sql: &mut String, platform: &PlatformSpec) {
    let category = match platform.category {
        Some(category) => format!("'{}'", variant(&category)),
        None => "NULL".to_owned(),
    };
    let (values, updates) = pricing_columns(
        platform.msrp_cents,
        &platform.vendor_offers,
        &platform.allowed_colorways,
        platform.default_colorway,
    );
    sql.push_str(&format!(
        "INSERT INTO platforms (id, sku, name, category, plate_cuts, sizes, msrp_cents, vendor_offers, allowed_colorways, default_colorway) VALUES ('{}', '{}', '{}', {}, '{}', '{}', {})\n\
         ON CONFLICT (id) DO UPDATE SET sku = excluded.sku, name = excluded.name, category = excluded.category, plate_cuts = excluded.plate_cuts, sizes = excluded.sizes, {updates};\n",
        platform.id,
        esc(&platform.sku),
        esc(&platform.name),
        category,
        json(&platform.plate_cuts),
        json(&platform.sizes),
        values,
    ));
}

/// Upsert one mount-slot row (grid dims NULL when the slot has no PALS grid).
fn slot_row(sql: &mut String, platform: &PlatformSpec, slot: &MountSlot) {
    let (pals_cols, pals_rows) = slot
        .pals_grid
        .as_ref()
        .map(|g| (Some(g.cols as i64), Some(g.rows as i64)))
        .unwrap_or((None, None));
    sql.push_str(&format!(
        "INSERT INTO mount_slots (platform_id, slot_id, label, interface, anchor, pals_cols, pals_rows) VALUES ('{}', '{}', '{}', '{}', '{}', {}, {})\n\
         ON CONFLICT (platform_id, slot_id) DO UPDATE SET label = excluded.label, interface = excluded.interface, anchor = excluded.anchor, pals_cols = excluded.pals_cols, pals_rows = excluded.pals_rows;\n",
        platform.id,
        esc(&slot.id),
        esc(&slot.label),
        variant(&slot.interface),
        json(&slot.anchor),
        pals_cols.map(|v| v.to_string()).unwrap_or("NULL".into()),
        pals_rows.map(|v| v.to_string()).unwrap_or("NULL".into()),
    ));
}

/// Upsert one component row.
fn component_row(sql: &mut String, component: &ComponentSpec) {
    let (pals_cols, pals_rows) = component
        .pals_footprint
        .map(|f| (Some(f.cols as i64), Some(f.rows as i64)))
        .unwrap_or((None, None));
    let (values, updates) = pricing_columns(
        component.msrp_cents,
        &component.vendor_offers,
        &component.allowed_colorways,
        component.default_colorway,
    );
    sql.push_str(&format!(
        "INSERT INTO components (id, sku, name, kind, interface, anchor, pals_cols, pals_rows, msrp_cents, vendor_offers, allowed_colorways, default_colorway, capabilities) VALUES ('{}', '{}', '{}', '{}', '{}', '{}', {}, {}, {}, '{}')\n\
         ON CONFLICT (id) DO UPDATE SET sku = excluded.sku, name = excluded.name, kind = excluded.kind, interface = excluded.interface, anchor = excluded.anchor, pals_cols = excluded.pals_cols, pals_rows = excluded.pals_rows, {updates}, capabilities = excluded.capabilities;\n",
        component.id,
        esc(&component.sku),
        esc(&component.name),
        variant(&component.kind),
        variant(&component.interface),
        json(&component.anchor),
        pals_cols.map(|v| v.to_string()).unwrap_or("NULL".into()),
        pals_rows.map(|v| v.to_string()).unwrap_or("NULL".into()),
        values,
        json(&component.capabilities),
    ));
}

/// Upsert one adapter-bridge row.
fn adapter_row(sql: &mut String, adapter: &AdapterBridge) {
    let (values, updates) = pricing_columns(
        adapter.msrp_cents,
        &adapter.vendor_offers,
        &adapter.allowed_colorways,
        adapter.default_colorway,
    );
    sql.push_str(&format!(
        "INSERT INTO adapter_bridges (id, sku, name, platform_interface, component_interface, anchor, msrp_cents, vendor_offers, allowed_colorways, default_colorway) VALUES ('{}', '{}', '{}', '{}', '{}', '{}', {})\n\
         ON CONFLICT (id) DO UPDATE SET sku = excluded.sku, name = excluded.name, platform_interface = excluded.platform_interface, component_interface = excluded.component_interface, anchor = excluded.anchor, {updates};\n",
        adapter.id,
        esc(&adapter.sku),
        esc(&adapter.name),
        variant(&adapter.platform_interface),
        variant(&adapter.component_interface),
        json(&adapter.anchor),
        values,
    ));
}

/// Upsert one role-preset row.
fn preset_row(sql: &mut String, preset: &RolePreset) {
    let role = preset
        .role
        .as_ref()
        .map(|role| format!("'{}'", variant(role)))
        .unwrap_or_else(|| "NULL".to_owned());
    sql.push_str(&format!(
        "INSERT INTO role_presets (preset_id, name, role, policy, platform_sku, default_colorway, placements) VALUES ('{}', '{}', {}, '{}', '{}', '{}', '{}')\n\
         ON CONFLICT (preset_id) DO UPDATE SET name = excluded.name, role = excluded.role, policy = excluded.policy, platform_sku = excluded.platform_sku, default_colorway = excluded.default_colorway, placements = excluded.placements;\n",
        esc(&preset.preset_id),
        esc(&preset.name),
        role,
        variant(&preset.policy),
        esc(&preset.platform_sku),
        variant(&preset.default_colorway),
        json(&preset.placements),
    ));
}

fn platforms(sql: &mut String, list: &[PlatformSpec]) {
    sql.push_str("-- Platforms and their mount slots.\n");
    for platform in list {
        platform_row(sql, platform);
        for slot in &platform.slots {
            slot_row(sql, platform, slot);
        }
    }
    sql.push('\n');
}

fn components(sql: &mut String, list: &[ComponentSpec]) {
    sql.push_str("-- Starter child components.\n");
    for component in list {
        component_row(sql, component);
    }
    sql.push('\n');
}

fn adapter_bridges(sql: &mut String, list: &[AdapterBridge]) {
    sql.push_str("-- Aftermarket adapter bridges.\n");
    for adapter in list {
        adapter_row(sql, adapter);
    }
    sql.push('\n');
}

fn role_presets(sql: &mut String, list: &[RolePreset]) {
    if list.is_empty() {
        return;
    }
    sql.push_str("-- Curated role presets.\n");
    for preset in list {
        preset_row(sql, preset);
    }
    sql.push('\n');
}
